export type TranslationKey = keyof typeof translations;

/**
 * Returns the translated string for the given locale and key.
 * Falls back to English for unknown locales or "other".
 */
export function t(locale: Locale, key: TranslationKey): string {
  const entry = translations[key];
  if (!entry) return String(key);

  const lang = locale ?? "en";

  // If locale is "other" or not found in the map, fall back to English
  if (lang === "other" || !(lang in entry)) {
    return entry.en;
  }

  return entry[lang as keyof TranslationMap];
}
